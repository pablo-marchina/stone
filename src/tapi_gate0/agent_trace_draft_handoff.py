"""Local synthetic recommendation trace -> explicitly authored editable draft.

The trace is provenance, never a grant. The host must authenticate an editor
or admin separately. No creative text is generated by the agent, no external
reference is accepted, and no production route invokes this adapter.
"""
from __future__ import annotations

from hashlib import sha256
from uuid import uuid4
import json

from sqlalchemy import insert, select
from sqlalchemy.exc import SQLAlchemyError

from .agent_graph_checkpoints import (
    agent_graph_events, agent_graph_runs, resume_run, _lock_tenant,
)
from .agent_graph_readonly_runner import LocalGraphPlan, plan_digest, _node_result
from .agent_draft_a05 import CreateAgentDraft
from .agent_evidence_b2 import EvidenceRetriever
from .sa_store import domain_events, outbox
from .storage import now_utc
from .studio_e1 import CreativeSpec, StudioStore

VERSION = "tapi-local-agent-trace-draft.v1"
AGGREGATE = "agent_trace_draft"
EVENT = "agent.trace_draft.created"


class TraceDraftDenied(ValueError):
    """Fixed denial codes; no evidence or editorial text in exceptions."""


def _deny(code):
    raise TraceDraftDenied("TRACE_DRAFT_" + code)


def create_trace_bound_draft(engine, *, tenant: str, actor: str, run_id: str,
                             plan: LocalGraphPlan, payload: CreateAgentDraft):
    """Revalidate terminal trace, B2 reference and write draft + audit atomically.

    Only a local SQLite fixture and a completed recommendation trace from the
    authenticated actor qualify. The brief is supplied independently by the
    operator; it is not claimed to be generated or validated by the trace.
    """
    if engine.dialect.name != "sqlite":
        _deny("LOCAL_SQLITE_REQUIRED")
    if type(plan) is not LocalGraphPlan or type(payload) is not CreateAgentDraft:
        _deny("VALIDATED_INPUT_REQUIRED")
    try:
        plan = LocalGraphPlan.model_validate(plan.model_dump(mode="python"))
        payload = CreateAgentDraft.model_validate(payload.model_dump(mode="python"))
    except (ValueError, TypeError):
        _deny("VALIDATED_INPUT_REQUIRED")
    if plan.mode != "recomendar" or payload.reference_grant_ids:
        _deny("SYNTHETIC_RECOMMENDATION_REQUIRED")
    if payload.brief.reference_content_ids != [plan.content_id]:
        _deny("REFERENCE_SCOPE_MISMATCH")
    try:
        with engine.begin() as db:
            # SQLite RESERVED write lock before any evidence or ledger read.
            _lock_tenant(db, tenant)
            trace = resume_run(engine, tenant=tenant, actor=actor, run_id=run_id,
                               connection=db)
            plan_sha = plan_digest(plan)
            stored_plan = db.scalar(select(agent_graph_runs.c.plan_sha256).where(
                agent_graph_runs.c.tenant_id == tenant,
                agent_graph_runs.c.run_id == run_id))
            if trace["mode"] != plan.mode or stored_plan != plan_sha:
                _deny("PLAN_MISMATCH")
            if trace["status"] != "TRACE_RECORDED":
                _deny("TERMINAL_TRACE_REQUIRED")
            history = db.execute(select(agent_graph_events.c.node,
                agent_graph_events.c.outcome, agent_graph_events.c.receipt_sha256).where(
                    agent_graph_events.c.tenant_id == tenant,
                    agent_graph_events.c.run_id == run_id).order_by(
                        agent_graph_events.c.sequence)).all()
            if len(history) != trace["revision"]:
                _deny("LEDGER_DRIFT")
            for node, outcome, digest in history:
                if _node_result(engine, tenant, plan, node, connection=db) != (outcome, digest):
                    _deny("SOURCE_DRIFT_RESTART_REQUIRED")
            # Existing B2 gate is authoritative independently of the trace.
            handoff = EvidenceRetriever(engine).handoff(tenant, payload.brief, connection=db)
            spec = CreativeSpec.model_validate(handoff.model_dump(mode="json"))
            doc = StudioStore(engine).create(tenant, actor, spec, payload.document_id,
                                             connection=db)
            provenance = {
                "schema_version": VERSION,
                "trace_chain_sha256": trace["chain_sha256"],
                "plan_sha256": plan_sha,
                "trace_revision": trace["revision"],
                "initial_document_sha256": sha256(doc.model_dump_json().encode()).hexdigest(),
                "initial_document_version": 1,
                "operator_brief_sha256": sha256(json.dumps(
                    payload.brief.model_dump(mode="json"), sort_keys=True,
                    separators=(",", ":"), ensure_ascii=False).encode()).hexdigest(),
                "operator_authored_brief": True,
                "scientific_validation": False,
                "external_rights_verified": False,
                "publication_allowed": False,
                "production_approved": False,
            }
            seq = db.execute(insert(domain_events).values(
                event_id=str(uuid4()), tenant_id=tenant, aggregate_type=AGGREGATE,
                aggregate_id=doc.document_id, event_type=EVENT, aggregate_version=1,
                occurred_at=now_utc().isoformat(),
                payload=json.dumps(provenance, sort_keys=True, separators=(",", ":")),
            )).inserted_primary_key[0]
            db.execute(insert(outbox).values(seq=seq, attempts=0, dead_letter=0))
            return doc
    except SQLAlchemyError:
        _deny("TRANSACTION_ABORTED")
