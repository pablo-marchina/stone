"""IMP-063: independent local VAD experiment; only generated PCM.

No Whisper checkpoint loaded, no speech transcription, no external media.
"""
from importlib.metadata import version
from pathlib import Path
from time import perf_counter
import math
import os
import shutil
import struct
import tempfile

from .multimodal_asr import (ASR_VERSION,SAMPLE_RATE,MAX_BYTES,CHALLENGE_SPEECH,
    _file_hash,_negative_pcm,_speech_pcm,require_temp_capacity)
from .multimodal_temporal import _run
from hashlib import sha256

VERSION="bd-vad-fixture.v1"
OPTIONS={"threshold":0.5,"min_speech_duration_ms":250,
         "min_silence_duration_ms":300,"speech_pad_ms":150}
MIN_IOU=0.60
MAX_BOUNDARY_ERROR_S=0.75
MAX_NEGATIVE_SECONDS=0.0

class VADError(ValueError):
    pass


def _validate_pcm(raw):
    if not raw or len(raw)%2 or len(raw)>MAX_BYTES:
        raise VADError("VAD_PCM_INVALID")
    return len(raw)//2


def validate_intervals(intervals,n):
    out=[]
    last=0
    for item in intervals:
        if len(out)>=64 or not isinstance(item,dict) or set(item)!={"start","end"}:
            raise VADError("VAD_INTERVAL_INVALID")
        a,b=item["start"],item["end"]
        if type(a) is not int or type(b) is not int or not last<=a<b<=n:
            raise VADError("VAD_INTERVAL_INVALID")
        out.append({"start":a,"end":b})
        last=b
    return out


def score_intervals(observed,expected,n):
    observed=validate_intervals(observed,n)
    expected=validate_intervals(expected,n)
    actual=sum(x["end"]-x["start"] for x in observed)
    target=sum(x["end"]-x["start"] for x in expected)
    overlap=sum(max(0,min(a["end"],b["end"])-max(a["start"],b["start"]))
                for a in observed for b in expected)
    union=actual+target-overlap
    iou=overlap/union if union else None
    boundary_error=None
    if len(observed)==len(expected) and expected:
        boundary_error=max(abs(a[k]-b[k])/SAMPLE_RATE for a,b in zip(observed,expected) for k in ("start","end"))
    passed=(iou is not None and iou>=MIN_IOU and boundary_error is not None and boundary_error<=MAX_BOUNDARY_ERROR_S) if expected else actual==0
    return {"expected_speech_s":target/SAMPLE_RATE,"detected_speech_s":actual/SAMPLE_RATE,
            "overlap_s":overlap/SAMPLE_RATE,"false_positive_s":(actual-overlap)/SAMPLE_RATE,
            "missed_speech_s":(target-overlap)/SAMPLE_RATE,"iou":iou,
            "max_boundary_error_s":boundary_error,"passed":bool(passed)}


def _trim_synthetic(raw):
    # Reference is the known inserted TTS region, not human phoneme annotation.
    # Trim only exact-zero padding generated by the local synthesizer.
    samples=list(struct.unpack("<"+"h"*_validate_pcm(raw),raw))
    nonzero=[i for i,v in enumerate(samples) if v]
    if not nonzero:
        raise VADError("VAD_EMPTY_SPEECH_FIXTURE")
    return raw[2*nonzero[0]:2*(nonzero[-1]+1)]


def _gain(raw,factor):
    return b"".join(struct.pack("<h",round(v*factor)) for (v,) in struct.iter_unpack("<h",raw))


def _mix(raw,background):
    import itertools
    a=struct.iter_unpack("<h",raw)
    b=itertools.cycle(struct.iter_unpack("<h",background))
    return b"".join(struct.pack("<h",max(-32768,min(32767,x[0]+y[0]))) for x,y in zip(a,b))


def fixture_rows(espeak,ffmpeg,temp):
    out=[]
    for cid,text,rate in CHALLENGE_SPEECH[:3]:
        speech=_trim_synthetic(_speech_pcm(espeak,ffmpeg,temp,cid,text,rate))
        n=len(speech)//2
        prefix=2*SAMPLE_RATE
        suffix=SAMPLE_RATE
        raw=bytes(2*prefix)+speech+bytes(2*suffix)
        out.append((cid+"_padded",raw,[{"start":prefix,"end":prefix+n}]))
        if cid=="inventory":
            out.append(("quiet_speech",bytes(2*prefix)+_gain(speech,0.25)+bytes(2*suffix),
                        [{"start":prefix,"end":prefix+n}]))
            out.append(("speech_with_noise",_mix(raw,_gain(_negative_pcm("noise"),0.25)),
                        [{"start":prefix,"end":prefix+n}]))
        if cid=="costs":
            gap=2*SAMPLE_RATE
            out.append(("two_speech_regions",speech+bytes(2*gap)+speech,
                        [{"start":0,"end":n},{"start":n+gap,"end":2*n+gap}]))
    for cid in ("silence","tone","noise"):
        out.append((cid,_negative_pcm(cid),[]))
    return out


def inspect_pcm(raw,detector):
    n=_validate_pcm(raw)
    import numpy as np
    pcm=np.frombuffer(raw,dtype="<i2").astype(np.float32)/32768
    t=perf_counter()
    observed=validate_intervals(detector(pcm),n)
    elapsed=round((perf_counter()-t)*1000,3)
    return {"pcm_sha256":sha256(raw).hexdigest(),"duration_s":n/SAMPLE_RATE,
            "intervals":observed,"inference_ms":elapsed,"timestamp_kind":"decoded_pcm_sample_indices"}


def run_vad_fixture_benchmark():
    os.environ.update(HF_HUB_OFFLINE="1",TRANSFORMERS_OFFLINE="1",HF_HUB_DISABLE_TELEMETRY="1")
    if version("faster-whisper")!=ASR_VERSION:
        raise VADError("VAD_RUNTIME_VERSION_MISMATCH")
    require_temp_capacity()
    espeak,ffmpeg=shutil.which("espeak-ng"),shutil.which("ffmpeg")
    if not espeak or not ffmpeg:
        raise VADError("VAD_LOCAL_BINARY_UNAVAILABLE")
    from faster_whisper.utils import get_assets_path
    from faster_whisper.vad import VadOptions,get_speech_timestamps,get_vad_model
    model=Path(get_assets_path())/"silero_vad_v6.onnx"
    if not model.is_file() or model.is_symlink() or not 0<model.stat().st_size<=30_000_000:
        raise VADError("VAD_LOCAL_ASSET_REQUIRED")
    digest=_file_hash(model)
    options=VadOptions(**OPTIONS)
    get_vad_model.cache_clear()
    try:
        get_vad_model()
        def detector(pcm):
            return get_speech_timestamps(pcm,options,sampling_rate=SAMPLE_RATE)
        cases=[]
        with tempfile.TemporaryDirectory(prefix="tapi-vad-fixtures-") as temp:
            for cid,raw,expected in fixture_rows(espeak,ffmpeg,temp):
                obs=inspect_pcm(raw,detector)
                cases.append({"case_id":cid,"expected_regions":expected,**obs,
                              **score_intervals(obs["intervals"],expected,len(raw)//2)})
        if _file_hash(model)!=digest:
            raise VADError("VAD_ASSET_CHANGED")
    finally:
        get_vad_model.cache_clear()
    positives=[c for c in cases if c["expected_regions"]]
    negatives=[c for c in cases if not c["expected_regions"]]
    return {"status":"VAD_FIXTURE_BENCHMARK_COMPLETED","policy_version":VERSION,"synthetic_only":True,
            "asset":"silero_vad_v6.onnx","asset_sha256":digest,"asset_independently_verified":False,
            "runtime_versions":{"faster-whisper":ASR_VERSION,"onnxruntime":version("onnxruntime"),
                "numpy":version("numpy"),"espeak-ng":_run(espeak,["--version"]).decode("utf-8","replace").splitlines()[0],
                "ffmpeg":_run(ffmpeg,["-version"]).decode("utf-8","replace").splitlines()[0]},
            "options":OPTIONS,"cases":cases,"cases_passed":sum(c["passed"] for c in cases),"cases_total":len(cases),
            "positive_cases":len(positives),"negative_cases":len(negatives),
            "mean_positive_iou":sum(c["iou"] or 0 for c in positives)/len(positives),
            "negative_false_positive_s":sum(c["false_positive_s"] for c in negatives),
            "engineering_gate_passed":len(positives)==6 and len(negatives)==3 and all(c["passed"] for c in cases),
            "gate_criteria":{"min_positive_iou":MIN_IOU,"max_boundary_error_s":MAX_BOUNDARY_ERROR_S,
                             "max_negative_speech_s":MAX_NEGATIVE_SECONDS,"all_cases_required":True},
            "reference_kind":"inserted_synthetic_tts_region_not_phoneme_gold",
            "whisper_checkpoint_loaded":False,"asr_integration_evaluated":False,
            "independent_gold":False,"real_media_processed":0,"real_media_processing_allowed":False,
            "external_data_accessed":False,"database_mutated":False,"scientific_admissions":0,
            "rubric_assessments_written":0,"production_approved":False}
